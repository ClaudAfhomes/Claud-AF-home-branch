const fs = require('node:fs');
const ts = require('typescript');
const { z } = require('zod');
const compiled = ts.transpileModule(fs.readFileSync('src/lib/cmsValidation.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const loaded = { exports: {} };
new Function('require', 'exports', compiled)(require, loaded.exports);
const cases = Object.entries(loaded.exports.documentSchemas).map(([key, schema]) => {
  const json = JSON.stringify(z.toJSONSchema(schema, { target: 'draft-7', unrepresentable: 'any' }));
  return `when '${key}' then extensions.jsonb_matches_schema($schema$${json}$schema$::json, document)`;
});
const outputPath = process.argv[2] ?? 'supabase-validation.sql';
fs.writeFileSync(outputPath, `-- Generated by node scripts/generate-cms-validation.cjs. Do not edit by hand.\ncreate extension if not exists pg_jsonschema with schema extensions;\ncreate or replace function public.validate_cms_document(document_key text, document jsonb)\nreturns boolean language sql immutable set search_path = '' as $function$\nselect case document_key\n${cases.join('\n')}\nelse false end;\n$function$;\nrevoke all on function public.validate_cms_document(text,jsonb) from public;\n`);
